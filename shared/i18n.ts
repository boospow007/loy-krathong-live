export function translate(text: string | undefined, locale: Locale): string {
  if (!text) return ''
  return locale === 'en' ? english[text] ?? text : text
}
export function localizedCountryName(name: string, locale: Locale): string {
  const match = name.match(/^(.+?)\s*\((.+)\)$/)
  return match ? (locale === 'en' ? match[2]! : match[1]!) : name
}
